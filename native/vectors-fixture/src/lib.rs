//! Access to `vectors.json` for the port tests.
//!
//! `vectors.json` is the reference capture taken from the device: each port is validated against it
//! to reproduce byte-for-byte what the closed libraries do.
//!
//! The point of this crate is that **a test must not pass green without having checked anything**.
//! Previously each `tests/vectors.rs` did `let Some(x) = load() else { return }`, so a missing,
//! broken, or incomplete `vectors.json` still passed. Those three situations are distinct and are
//! handled differently here:
//!
//! | situation                                   | outcome          |
//! |---------------------------------------------|------------------|
//! | neither file exists                         | skipped (notice) |
//! | neither exists and required by env          | fails            |
//! | exists but fails to parse                   | fails            |
//! | exists and is missing the requested section | fails            |
//!
//! It looks for `vectors.json` first (the real capture, local and gitignored) and falls back to
//! `vectors.sample.json` (the synthetic sample, checked in). That way PRs include real validation
//! tests without leaking the device's `ANDROID_ID`.
//!
//! To require the file: `CADENCE_VECTORS_REQUIRED=1 cargo test`. That is what CI runs so a checkout
//! without the capture is never misread as "all good".

use std::path::{Path, PathBuf};

/// Environment variable that makes the capture mandatory (CI sets it to 1).
pub const ENV_REQUIRED: &str = "CADENCE_VECTORS_REQUIRED";

/// Environment variable pointing directly to the capture without deriving it from the crate.
///
/// The normal path comes from `CARGO_MANIFEST_DIR`, which is fixed **at compile time** and points
/// to the build machine's directory. A test binary cross-compiled for Android and run on the device
/// lacks that path, so the capture is passed via this variable there. When set, it overrides
/// everything else, and if it points to a nonexistent file it fails: whoever set it wanted that file.
pub const ENV_FILE: &str = "CADENCE_VECTORS_FILE";

/// Real device capture (gitignored: contains its ANDROID_ID and GUID).
const REAL: &str = "../vectors.json";
/// Synthetic sample checked into the repo, generated by `cargo run --example ...` in
/// `native/device-guid`; consistent with its own synthetic ANDROID_ID so tests still validate the algorithm.
const MUESTRA: &str = "../vectors.sample.json";

fn required() -> bool {
    std::env::var(ENV_REQUIRED).map(|v| v != "0" && !v.is_empty()).unwrap_or(false)
}

/// Full capture, or `None` if absent (and not required).
///
/// # Panics
/// If the file exists and fails to parse as JSON, or if it does not exist and
/// `CADENCE_VECTORS_REQUIRED` is set. A corrupt file is a failure, not a skipped test.
pub fn load(manifest_dir: &str) -> Option<serde_json::Value> {
    load_with_required(manifest_dir, required())
}

/// Like [`load`], but with an explicit "is the capture required?" flag instead of reading env.
///
/// Exists so this crate's own tests can exercise both branches without depending on whether
/// `CADENCE_VECTORS_REQUIRED` is set in the shell running them (which `test-ports.sh` does).
pub fn load_with_required(manifest_dir: &str, require: bool) -> Option<serde_json::Value> {
    let forced = std::env::var_os(ENV_FILE).map(PathBuf::from);
    load_from(manifest_dir, require, forced)
}

/// Which file to read: the explicit override if given, otherwise the real capture, otherwise the sample.
pub fn resolve_path(manifest_dir: &str, forced: Option<PathBuf>) -> PathBuf {
    if let Some(p) = forced {
        return p;
    }
    let real = Path::new(manifest_dir).join(REAL);
    if real.exists() { real } else { Path::new(manifest_dir).join(MUESTRA) }
}

/// [`load_with_required`] with an explicit forced path, so it can be tested without mutating
/// process env (which all tests running in parallel share).
pub fn load_from(manifest_dir: &str, require: bool, forced: Option<PathBuf>) -> Option<serde_json::Value> {
    // An explicitly specified file is always required: if missing, fail rather than skip.
    let require = require || forced.is_some();
    let path = resolve_path(manifest_dir, forced);
    match std::fs::read_to_string(&path) {
        Ok(text) => Some(serde_json::from_str(&text).unwrap_or_else(|e| {
            panic!("vectors.json exists at {} but failed to parse: {e}", path.display())
        })),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            assert!(
                !require,
                "{ENV_REQUIRED} is set and neither {REAL} nor {MUESTRA} exists next to {}",
                manifest_dir
            );
            eprintln!("notice: missing {} -> test skipped", path.display());
            None
        }
        Err(e) => panic!("could not read {}: {e}", path.display()),
    }
}

/// A section from the capture. If the file exists, the section **must** be present.
///
/// # Panics
/// If the capture exists and is missing `key`: that is the exact case that previously passed green.
pub fn section(manifest_dir: &str, key: &str) -> Option<serde_json::Value> {
    Some(section_in(&load(manifest_dir)?, key))
}

/// A string section (the `userAgent` case).
pub fn string_section(manifest_dir: &str, key: &str) -> Option<String> {
    Some(string_in(&load(manifest_dir)?, key))
}

/// Section `key` from an already-loaded capture. Panics if missing or null.
pub fn section_in(v: &serde_json::Value, key: &str) -> serde_json::Value {
    let s = v.get(key).unwrap_or_else(|| {
        panic!(
            "vectors.json missing section {key:?} (has: {})",
            v.as_object()
                .map(|o| o.keys().cloned().collect::<Vec<_>>().join(", "))
                .unwrap_or_else(|| "not an object".into())
        )
    });
    assert!(!s.is_null(), "vectors.json has {key:?} as null");
    s.clone()
}

/// [`section_in`] for a section that must be a string.
pub fn string_in(v: &serde_json::Value, key: &str) -> String {
    let s = section_in(v, key);
    s.as_str()
        .unwrap_or_else(|| panic!("vectors.json: {key:?} should be a string, got {s}"))
        .to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicU32, Ordering};

    /// Un directorio temporal con el archivo de captura que se le pida, y el
    /// `manifest_dir` que hay que pasarle a [`load`] (la captura se busca en `..`).
    struct Case {
        root: PathBuf,
    }

    impl Case {
        fn new(name: &str, content: Option<(&str, &str)>) -> Self {
            static N: AtomicU32 = AtomicU32::new(0);
            let root = std::env::temp_dir()
                .join(format!("vectors-{name}-{}", N.fetch_add(1, Ordering::Relaxed)));
            let _ = std::fs::remove_dir_all(&root);
            std::fs::create_dir_all(root.join("fake_crate")).unwrap();
            if let Some((file, text)) = content {
                std::fs::write(root.join(file), text).unwrap();
            }
            Self { root }
        }
        fn manifest(&self) -> String {
            self.root.join("fake_crate").to_string_lossy().into_owned()
        }
    }

    impl Drop for Case {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.root);
        }
    }

    /// Capture for a test case, **ignoring the environment**: these tests also run with
    /// `CADENCE_VECTORS_FILE` and `CADENCE_VECTORS_REQUIRED` set (as invoked by the device
    /// runner), and they test this crate itself rather than the shell environment.
    fn load_case(c: &Case) -> Option<serde_json::Value> {
        load_from(&c.manifest(), false, None)
    }

    const GOOD: &str = r#"{"userAgent":"Music/5.0.2","ckcRequests":[1],"nullField":null}"#;

    #[test]
    fn reads_real_capture_when_present() {
        let c = Case::new("real", Some(("vectors.json", GOOD)));
        let v = load_case(&c).expect("should find it");
        assert_eq!(v["userAgent"], "Music/5.0.2");
    }

    /// Without the real capture, falls back to the checked-in sample.
    #[test]
    fn falls_back_to_sample() {
        let c = Case::new("sample", Some(("vectors.sample.json", GOOD)));
        assert_eq!(load_case(&c).expect("sample")["userAgent"], "Music/5.0.2");
    }

    /// With both present, the real capture wins: it matches the device under test.
    #[test]
    fn real_overrides_sample() {
        let c = Case::new("both", Some(("vectors.sample.json", r#"{"userAgent":"sample"}"#)));
        std::fs::write(c.root.join("vectors.json"), r#"{"userAgent":"real"}"#).unwrap();
        assert_eq!(load_case(&c).expect("real")["userAgent"], "real");
    }

    /// With neither present it skips, which is the only case where a test may not validate.
    #[test]
    fn no_capture_returns_none() {
        let c = Case::new("none", None);
        // explicit: when not required it skips, the only case where a test does not validate
        assert!(load_from(&c.manifest(), false, None).is_none());
    }

    /// A corrupt capture is a failure, not a skipped test: that is the exact gap this crate
    /// exists to close.
    #[test]
    #[should_panic(expected = "failed to parse")]
    fn corrupt_capture_panics() {
        let c = Case::new("corrupt", Some(("vectors.json", "{ not json")));
        let _ = load_case(&c);
    }

    /// If the capture is present, the section requested by the test **must** exist.
    #[test]
    #[should_panic(expected = "missing section")]
    fn missing_section_panics() {
        let c = Case::new("missing-section", Some(("vectors.json", GOOD)));
        let _ = section_in(&load_case(&c).unwrap(), "deviceGuid");
    }

    /// A null section cannot be used for validation either.
    #[test]
    #[should_panic(expected = "as null")]
    fn null_section_panics() {
        let c = Case::new("null", Some(("vectors.json", GOOD)));
        let _ = section_in(&load_case(&c).unwrap(), "nullField");
    }

    /// And if requested as a string, it must be a string.
    #[test]
    #[should_panic(expected = "should be a string")]
    fn non_string_section_panics() {
        let c = Case::new("non-string", Some(("vectors.json", GOOD)));
        let _ = string_in(&load_case(&c).unwrap(), "ckcRequests");
    }

    /// When the capture is required, missing it is a failure rather than a skip.
    #[test]
    #[should_panic(expected = "is set and neither")]
    fn missing_required_capture_panics() {
        let c = Case::new("required", None);
        let _ = load_from(&c.manifest(), true, None);
    }

    /// An explicit path overrides the crate's capture.
    #[test]
    fn explicit_path_overrides_everything() {
        let c = Case::new("forced", Some(("vectors.json", r#"{"userAgent":"from crate"}"#)));
        let other = c.root.join("other.json");
        std::fs::write(&other, r#"{"userAgent":"forced"}"#).unwrap();
        let v = load_from(&c.manifest(), false, Some(other)).expect("forced");
        assert_eq!(v["userAgent"], "forced");
    }

    /// And if it points to a nonexistent file, it fails even when not required: whoever
    /// specified it wanted that specific file, not "whichever exists".
    #[test]
    #[should_panic(expected = "is set and neither")]
    fn nonexistent_explicit_path_panics() {
        let c = Case::new("forced-missing", Some(("vectors.json", GOOD)));
        let _ = load_from(&c.manifest(), false, Some(c.root.join("missing.json")));
    }

    #[test]
    fn string_section_is_read() {
        let c = Case::new("string", Some(("vectors.json", GOOD)));
        assert_eq!(string_in(&load_case(&c).unwrap(), "userAgent"), "Music/5.0.2");
    }

    /// `section` on a missing capture skips just like `load`: there is nothing to require.
    #[test]
    fn missing_capture_section_returns_none() {
        let c = Case::new("sec-none", None);
        assert!(load_from(&c.manifest(), false, None).is_none());
    }
}
